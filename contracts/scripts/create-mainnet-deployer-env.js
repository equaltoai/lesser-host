#!/usr/bin/env node
import { closeSync, existsSync, openSync, writeFileSync, chmodSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { Wallet } from "ethers";

const LIVE_SAFE = "0xfE63333F303D4f7b2354f7E3eca752C812D65907";
const LIVE_ENS_GATEWAY_SIGNER = "0x2ED2377e0377CFB8Cc428184FaE392cd1335F4af";
const LIVE_ENS_GATEWAY_URL = "https://lesser.host/resolve?sender={sender}&data={data}";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const contractsDir = resolve(scriptDir, "..");

function usage() {
  console.log(`Usage: node scripts/create-mainnet-deployer-env.js [--out <path>] [--force]

Creates a local-only mainnet deployer .env with a fresh random EOA private key.
The private key is written only to the output file and is never printed.

Defaults:
  --out .env

IMPORTANT: hardhat loads contracts/.env only (bare dotenv/config). A file
generated with a non-default --out is NOT picked up automatically; you must
run deploys with DOTENV_CONFIG_PATH pointing at it (the exact invocation is
printed after generation).

Environment:
  MAINNET_RPC_URL  Optional; copied into the generated file if already set.
  LESSER_WALLET    Optional; copied into the generated file if already set.
  SOUL_MINT_ATTESTOR Optional; copied into the generated file if already set.

Examples:
  node scripts/create-mainnet-deployer-env.js
  node scripts/create-mainnet-deployer-env.js --out .env.mainnet
  DOTENV_CONFIG_PATH=.env.mainnet npm run deploy:mainnet:all
`);
}

function parseArgs(argv) {
  const parsed = {
    out: ".env",
    force: false,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--help" || arg === "-h") {
      parsed.help = true;
    } else if (arg === "--force") {
      parsed.force = true;
    } else if (arg === "--out") {
      const value = argv[i + 1];
      if (!value) throw new Error("--out requires a path");
      parsed.out = value;
      i += 1;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return parsed;
}

function quoteEnv(value) {
  return JSON.stringify(value ?? "");
}

function writePrivateFile(path, contents, force) {
  if (existsSync(path) && !force) {
    throw new Error(`${path} already exists. Refusing to overwrite; pass --force only if you intend to rotate this key.`);
  }

  const fd = openSync(path, force ? "w" : "wx", 0o600);
  try {
    writeFileSync(fd, contents, "utf8");
  } finally {
    closeSync(fd);
  }
  chmodSync(path, 0o600);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    usage();
    return;
  }

  const outPath = resolve(contractsDir, args.out);
  const wallet = Wallet.createRandom();
  const now = new Date().toISOString();
  const mainnetRpcUrl = process.env.MAINNET_RPC_URL?.trim() ?? "";
  const lesserWallet = process.env.LESSER_WALLET?.trim() ?? "";
  const soulMintAttestor = process.env.SOUL_MINT_ATTESTOR?.trim() ?? "";

  const contents = [
    "# Generated by contracts/scripts/create-mainnet-deployer-env.js",
    `# Created: ${now}`,
    "# Local-only mainnet deployer. DO NOT COMMIT.",
    "# Fund PUBLIC_DEPLOYER_ADDRESS with ETH for deployment gas.",
    "# The private key is a disposable deployer key; deployed contract ownership is assigned to the Safe below.",
    "",
    `MAINNET_RPC_URL=${quoteEnv(mainnetRpcUrl)}`,
    `DEPLOYER_PRIVATE_KEY=${quoteEnv(wallet.privateKey)}`,
    `PUBLIC_DEPLOYER_ADDRESS=${quoteEnv(wallet.address)}`,
    `INITIAL_OWNER=${quoteEnv(LIVE_SAFE)}`,
    "",
    "# OffchainResolver constructor args",
    `ENS_GATEWAY_SIGNER=${quoteEnv(LIVE_ENS_GATEWAY_SIGNER)}`,
    `ENS_GATEWAY_URL=${quoteEnv(LIVE_ENS_GATEWAY_URL)}`,
    "",
    "# Full live soul/tip contract deployment args",
    `LESSER_WALLET=${quoteEnv(lesserWallet)}`,
    "# 0 = souls are soulbound immediately at mint (transfers permanently blocked;",
    "# wallet rotation still works). claimWindowSeconds is immutable post-deploy.",
    "SOUL_CLAIM_WINDOW_SECONDS=\"0\"",
    "SOUL_MINT_FEE_WEI=\"500000000000000\"",
    `SOUL_MINT_ATTESTOR=${quoteEnv(soulMintAttestor)}`,
    "SOUL_MINT_SIGNER=\"\"",
    "SOUL_MINT_SIGNER_KEY_SSM_PARAM=\"/lesser-host/soul/live/mint-signer-key\"",
    "MAINNET_RPC_SSM_PARAM=\"/lesser-host/api/infura/mainnet\"",
    "# Optional comma-separated list like USDC:0x...,USDT:0x...; verify token addresses before setting.",
    "TIP_ALLOWED_TOKENS=\"\"",
    "",
  ].join("\n");

  writePrivateFile(outPath, contents, args.force);

  console.log(`Created ${outPath}`);
  console.log("Permissions: 0600");
  console.log(`Public deployer address to fund: ${wallet.address}`);
  console.log("Private key: written to file only (not printed)");
  console.log("Suggested funding depends on deployment scope; do not overfund this disposable deployer.");
  if (args.out !== ".env") {
    console.log("");
    console.log("NOTE: hardhat only auto-loads contracts/.env. To use this file, run:");
    console.log(`  DOTENV_CONFIG_PATH=${args.out} npm run deploy:mainnet:all`);
  }
  if (!mainnetRpcUrl) {
    console.log("Reminder: edit MAINNET_RPC_URL in the generated file before deploying.");
  }
  if (!lesserWallet) {
    console.log("Reminder: edit LESSER_WALLET before deploying the full soul/tip contract set.");
  }
  if (!soulMintAttestor) {
    console.log("Reminder: set SOUL_MINT_ATTESTOR before deploying the full soul/tip contract set.");
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
