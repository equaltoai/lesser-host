#!/usr/bin/env node
import { closeSync, existsSync, openSync, writeFileSync, chmodSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { Wallet } from "ethers";

const DEFAULT_SSM_PARAM = "/lesser-host/soul/live/mint-signer-key";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const contractsDir = resolve(scriptDir, "..");

function usage() {
  console.log(`Usage: node scripts/create-mainnet-mint-signer-env.js [--out <path>] [--force]

Creates a local-only mainnet soul mint attestor env file with a fresh random key.
The private key is written only to the output file and is never printed.

Defaults:
  --out .env.mint-signer-live

The generated SOUL_MINT_ATTESTOR address is the address to add with
SoulRegistry.addAttestor(...) after the SoulRegistry mainnet deployment.
`);
}

function parseArgs(argv) {
  const parsed = {
    out: ".env.mint-signer-live",
    force: false,
    help: false,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--help" || arg === "-h") {
      parsed.help = true;
    } else if (arg === "--force") {
      parsed.force = true;
    } else if (arg === "--out") {
      const value = argv[i + 1];
      if (!value) throw new Error("--out requires a path");
      parsed.out = value;
      i += 1;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return parsed;
}

function quoteEnv(value) {
  return JSON.stringify(value ?? "");
}

function writePrivateFile(path, contents, force) {
  if (existsSync(path) && !force) {
    throw new Error(`${path} already exists. Refusing to overwrite; pass --force only if you intend to rotate this key.`);
  }

  const fd = openSync(path, force ? "w" : "wx", 0o600);
  try {
    writeFileSync(fd, contents, "utf8");
  } finally {
    closeSync(fd);
  }
  chmodSync(path, 0o600);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    usage();
    return;
  }

  const outPath = resolve(contractsDir, args.out);
  const wallet = Wallet.createRandom();
  const now = new Date().toISOString();

  const contents = [
    "# Generated by contracts/scripts/create-mainnet-mint-signer-env.js",
    `# Created: ${now}`,
    "# Local-only mainnet soul mint attestor. DO NOT COMMIT.",
    "# Store SOUL_MINT_SIGNER_PRIVATE_KEY in SSM as a SecureString; never print it.",
    "",
    `SOUL_MINT_SIGNER_KEY_SSM_PARAM=${quoteEnv(DEFAULT_SSM_PARAM)}`,
    `SOUL_MINT_ATTESTOR=${quoteEnv(wallet.address)}`,
    `SOUL_MINT_SIGNER=${quoteEnv(wallet.address)}`,
    `SOUL_MINT_SIGNER_PRIVATE_KEY=${quoteEnv(wallet.privateKey)}`,
    "",
  ].join("\n");

  writePrivateFile(outPath, contents, args.force);

  console.log(`Created ${outPath}`);
  console.log("Permissions: 0600");
  console.log(`Soul mint attestor address: ${wallet.address}`);
  console.log("Private key: written to file only (not printed)");
  console.log("Store in SSM without echoing the value, for example:");
  console.log(`  set -a; source ${outPath}; set +a`);
  console.log('  aws ssm put-parameter --name "$SOUL_MINT_SIGNER_KEY_SSM_PARAM" --value "$SOUL_MINT_SIGNER_PRIVATE_KEY" --type SecureString --overwrite');
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
